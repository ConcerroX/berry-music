private val autonymCache = mutableMapOf<String, String>()

/** "Name (code)", using the language's own name when the platform provides one. */
internal fun languageLabel(option: LanguageOption): String {
    val name = autonymCache.getOrPut(option.code) {
        platformLanguageAutonym(option.code, option.alpha2) ?: option.name
    }
    return "$name (${option.code})"
}

internal fun displayLanguage(value: String): String =
    LANGUAGE_OPTIONS.firstOrNull {
        it.code.equals(value, ignoreCase = true) ||
            (it.legacyCode.isNotEmpty() && it.legacyCode.equals(value, ignoreCase = true))
    }?.let(::languageLabel) ?: value

internal fun LanguageOption.matchesQuery(query: String): Boolean =
    name.contains(query, ignoreCase = true) ||
        code.contains(query, ignoreCase = true) ||
        legacyCode.contains(query, ignoreCase = true) ||
        alpha2.contains(query, ignoreCase = true) ||
        languageLabel(this).contains(query, ignoreCase = true)
